def is_workday(day):

    # Суббота и воскресенье
    if day.weekday() >= 5:
        return False

    # Дополнительные выходные
    if day in HOLIDAYS:
        return False

    return True


def workdays_between(start, end):

    days = 0
    current = start

    while current <= end:

        if is_workday(current):
            days += 1

        current += timedelta(days=1)

    return days


def send(text):

    url = f"https://api.telegram.org/bot{BOT_TOKEN}/sendMessage"

    requests.post(
        url,
        json={
            "chat_id": CHAT_ID,
            "text": text
        },
        timeout=20
    ).raise_for_status()


