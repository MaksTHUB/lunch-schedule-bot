    # В выходные ничего не отправляем
    if not is_workday(today):
        return

    # Сколько рабочих дней прошло с 04.09.2026
    day_number = workdays_between(START_DATE, today) - 1

    # 0 → первый вариант
    # 1 → второй
    # 2 → третий
    # затем снова 0
    shift = day_number % 3

    # Сдвигаем расписание по кругу
